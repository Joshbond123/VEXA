import runtimeSource from '../runtime/vexa_runtime.py';

export function buildKernel(cfg) {
  const config = {
    workerUrl: cfg.baseUrl,
    runtimeKey: cfg.runtimeKey,
    dataset: cfg.dataset,
    modelFile: cfg.modelFile,
    modelBytes: cfg.modelBytes,
    modelSha256: cfg.modelSha256,
    servedModel: cfg.servedModel,
    ctx: cfg.ctx,
    parallel: cfg.parallel,
    kernelSlug: cfg.kernelSlug,
    sessionNonce: cfg.sessionNonce,
    verifyFull: false,
    loadTimeoutSeconds: 1200,
    // Direct kernels serve the model over their own tunnel instead of polling the
    // Worker, so inference costs no Durable Object requests at all.
    direct: !!cfg.direct,
    directApiKey: cfg.directApiKey || '',
  };
  // JSON is not valid Python: emit a JSON string literal and decode it in the kernel.
  const literal = JSON.stringify(JSON.stringify(config));
  return [
    '# VEXA Kaggle GPU runtime (generated by the VEXA control plane).',
    'import json as _vexa_json',
    'CONFIG = _vexa_json.loads(' + literal + ')',
    '',
    runtimeSource,
  ].join('\n');
}
